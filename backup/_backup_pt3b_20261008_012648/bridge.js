api.listener.on("closed", (code, reason) => {
  log("âš ï¸ WebSocket closed:", code, reason);
  emit({ event: "closed", code, reason });

  if (isReconnecting) return;
  isReconnecting = true;

  if (reconnectAttempts >= MAX_RECONNECT) {
    log("âŒ ÄÃ£ thá»­ reconnect " + MAX_RECONNECT + " láº§n. ThoÃ¡t.");
    process.exit(1);
  }

  reconnectAttempts++;
  const delay = 8000;
  log(`ðŸ”„ Reconnect láº§n ${reconnectAttempts} sau ${delay / 1000}s...`);

  setTimeout(async () => {
    try {
      try { api.listener.stop(); } catch (e) {}

      const fresh = await getCredentials();
      if (!fresh || fresh.cookie.length < 2) {
        log("âŒ KhÃ´ng cÃ³ cookie");
        isReconnecting = false;
        return;
      }

      const zalo = new Zalo({ selfListen: true, imageMetadataGetter });
      const newApi = await zalo.login({
        cookie: fresh.cookie,
        imei: fresh.imei,
        userAgent: fresh.user_agent,
      });

      api = newApi;

      api.listener.on("message", m => { cacheMessage(m); emit({ event: "message", data: m }); });
      api.listener.on("undo", handleUndoEvent);
      api.listener.on("connected", () => {
        log("âœ… Reconnect OK");
        reconnectAttempts = 0;
        isReconnecting = false;
      });
      api.listener.on("error", (err) => log("âŒ Listener error:", err?.message || err));
      api.listener.on("closed", (c, r) => {
        log("âš ï¸ WS closed (sau reconnect):", c, r);
        isReconnecting = false;
      });

      api.listener.start();
      log("âœ… Reconnect thÃ nh cÃ´ng");
    } catch (e) {
      log("âŒ Reconnect tháº¥t báº¡i:", e?.message || e);
      isReconnecting = false;
    }
  }, delay);
});

api.listener.start();
